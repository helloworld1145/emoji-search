// 把所有组汇总成「字 → 混淆字集合」的反查表（含自身；同一字出现在多组时取并集）。
const CONFUSABLE = new Map<string, string[]>()
for (const group of GROUPS) {
  const chars = [...group]
  for (const c of chars) {
    const cur = CONFUSABLE.get(c) ?? []
    for (const x of chars) if (!cur.includes(x)) cur.push(x)
    CONFUSABLE.set(c, cur)
  }
}

/** 取某字的混淆字集合（至少包含自身） */
export function confusablesOf(ch: string): string[] {
  return CONFUSABLE.get(ch) ?? [ch]
}

// GLOB 字符类内部需要转义/剔除的特殊字符
const CLASS_SPECIAL = '[]-^\\'

/**
 * 把查询关键词构造为 SQLite GLOB 模糊匹配模式。
 *
 * 规则：
 * - 仅保留中文字、英文字母、数字；忽略标点/空格（OCR 噪声）与 GLOB 元字符（* ? [ ]）。
 * - 每个查询字若属于混淆组，则展开成字符类 [abc…]；否则按字面量匹配。
 *   （英文大小写也容错，展开为 [aA] 形式。）
 * - 整体为连续子串匹配：*<片段1><片段2>…*，即要求查询字的混淆替身按序连续出现，
 *   既修正「同音/形近错别字」，又避免完全无关的文本被命中。
 *
 * 返回 null 表示关键词中没有可模糊扩展的字（即精确 LIKE 已足够），调用方应直接走原逻辑，
 * 不引入额外的 GLOB 分支，保证普通查询行为不变、零额外开销。
 */
export function buildFuzzyGlob(keyword: string): string | null {
  const chars = [...keyword].filter(
    (ch) =>
      /[一-鿿A-Za-z0-9]/.test(ch) && ch !== '*' && ch !== '?' && ch !== '[' && ch !== ']'
  )
  if (chars.length === 0) return null

  const parts: string[] = []
  let hasFuzzy = false
  for (const ch of chars) {
    const group = confusablesOf(ch)
    if (group.length > 1) {
      hasFuzzy = true
      const cls = group.filter((c) => !CLASS_SPECIAL.includes(c)).join('')
      if (cls.length <= 1) parts.push(ch)
      else parts.push('[' + cls + ']')
    } else if (/[A-Za-z]/.test(ch)) {
      // 英文大小写容错（[aA] 形式）；但 LIKE 本身已对 ASCII 大小写不敏感，
      // 故仅作字面展开、不计入 hasFuzzy，避免纯英文查询误触发「近似匹配」提示。
      const lower = ch.toLowerCase()
      const upper = ch.toUpperCase()
      if (lower !== upper) parts.push('[' + lower + upper + ']')
      else parts.push(ch)
    } else {
      parts.push(ch)
    }
  }

  if (!hasFuzzy) return null
  return '*' + parts.join('') + '*'
}

/** 该关键词是否会触发近似（模糊）匹配，供 UI 提示用 */
export function isFuzzyKeyword(keyword: string): boolean {
  return buildFuzzyGlob(keyword) !== null
}
