/**
 * 归一化查询：小写去空格 → 精确命中 → 复数兜底（s/es/ies→y）→ 未命中返回空串。
 * 未收录的英文标签直接丢弃（用户选择整洁优先），不再保留英文原文入库，
 * 从而保证 emojis.tags 全中文、可被中文 LIKE 搜索命中。
 */
export function translateLabel(raw: string): string {
  const label = (raw ?? '').trim()
  if (!label) return ''
  const key = label.toLowerCase()
  if (LABEL_TO_CHINESE[key]) return LABEL_TO_CHINESE[key]
  const candidates: string[] = []
  if (key.endsWith('s')) {
    candidates.push(key.slice(0, -1))
    if (key.endsWith('es')) candidates.push(key.slice(0, -2))
    if (key.endsWith('ies')) candidates.push(key.slice(0, -3) + 'y')
  }
  for (const c of candidates) {
    const hit = LABEL_TO_CHINESE[c]
    if (hit) return hit
  }
  // 词典外英文标签丢弃（整洁优先），调用方已对空串做过滤
  return ''
}
